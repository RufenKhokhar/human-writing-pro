"""Refresh the portable prompt and create release ZIPs with checksums."""
from hashlib import sha256
from pathlib import Path
import re
from zipfile import ZipFile, ZIP_DEFLATED
from validate import ROOT, SKILL, validate


def portable_text():
    entry = (SKILL / 'SKILL.md').read_text(encoding='utf-8').split('---', 2)[2].strip()
    entry = re.sub(r'\[([^\]]+)\]\(references/([^)]+)\)',
                   r'\1 (included below under Reference: \2)', entry)
    sections = [
        '# Human Writing Pro — portable instructions\n\n'
        'Use these instructions for the writing task that follows. Reference '
        'sections are included inline; consult the ones relevant to the task. '
        'This does not install persistent skills or add tools to your assistant.\n\n'
        'Generated from the canonical skill files. Do not edit this file directly.',
        entry,
    ]
    for ref in sorted((SKILL / 'references').glob('*.md')):
        sections.append(f'# Reference: {ref.name}\n\n' + ref.read_text(encoding='utf-8').strip())
    sections.append('# License\n\n' + (ROOT / 'LICENSE').read_text(encoding='utf-8'))
    return '\n\n---\n\n'.join(sections) + '\n'


def build():
    prompt = ROOT / 'prompts' / 'human-writing-pro.md'
    prompt.parent.mkdir(exist_ok=True)
    prompt.write_text(portable_text(), encoding='utf-8', newline='\n')
    version = validate()
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    skill_zip = dist / f'human-writing-pro-{version}-skill.zip'
    repo_zip = dist / f'human-writing-pro-{version}-repository.zip'
    with ZipFile(skill_zip, 'w', ZIP_DEFLATED) as archive:
        for file in sorted(SKILL.rglob('*')):
            if file.is_file():
                archive.write(file, 'human-writing-pro/' + file.relative_to(SKILL).as_posix())
    with ZipFile(repo_zip, 'w', ZIP_DEFLATED) as archive:
        for file in sorted(ROOT.rglob('*')):
            relative = file.relative_to(ROOT)
            if file.is_file() and not any(p in {'dist', '.git', '__pycache__', '.venv'} for p in relative.parts):
                archive.write(file, 'human-writing-pro/' + relative.as_posix())
    checksums = ''.join(f'{sha256(file.read_bytes()).hexdigest()}  {file.name}\n'
                        for file in [skill_zip, repo_zip])
    (dist / 'SHA256SUMS.txt').write_text(checksums, encoding='utf-8', newline='\n')
    print(f'Built skill and repository archives in {dist}')


if __name__ == '__main__':
    build()
